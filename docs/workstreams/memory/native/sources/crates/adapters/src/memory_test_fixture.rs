//! Explicit-root synthetic store fixtures. No temp-directory fallback or runtime.
use std::{fs,io::Write,path::{Path,PathBuf}};
pub(crate) struct MemoryFixture{root:PathBuf,directory:PathBuf,marker:String}
fn plain(path:&Path)->Result<fs::Metadata,String>{
 let m=fs::symlink_metadata(path).map_err(|e|format!("{}: {e}",path.display()))?;
 if m.file_type().is_symlink(){return Err(format!("fixture symlink refused: {}",path.display()))}
 #[cfg(windows)]{use std::os::windows::fs::MetadataExt;if m.file_attributes()&0x400!=0{return Err(format!("fixture reparse point refused: {}",path.display()))}}
 Ok(m)
}
impl MemoryFixture{
 pub(crate) fn new()->Self{
  let configured=std::env::var_os("VEYRA_MEMORY_NATIVE_TEST_ROOT").expect("Root must set VEYRA_MEMORY_NATIVE_TEST_ROOT to the existing approved task output root; no fallback");
  let root=PathBuf::from(configured).canonicalize().expect("approved fixture root must exist");
  assert!(plain(&root).unwrap().is_dir());
  let id=uuid::Uuid::new_v4().to_string();let directory=root.join(format!("veyra-memory-native-{id}"));
  let marker=format!("synthetic-memory-store-fixture:{id}");
  let fixture=Self{root,directory,marker}; // Retain exact path even if setup fails.
  fs::create_dir(&fixture.directory).unwrap_or_else(|error|panic!("fixture create failed at {}: {error}",fixture.directory.display()));
  crate::service_registration::restrict_directory(&fixture.directory).unwrap();
  let mut f=fs::OpenOptions::new().write(true).create_new(true).open(fixture.directory.join("fixture-owner")).unwrap();
  f.write_all(fixture.marker.as_bytes()).unwrap();f.sync_all().unwrap();drop(f);
  fixture
 }
 pub(crate) fn directory(&self)->&Path{&self.directory}
 fn reconcile(&self)->Result<(),String>{
  let directory=self.directory.canonicalize().map_err(|e|e.to_string())?;
  if directory.parent()!=Some(self.root.as_path())||directory!=self.directory||!plain(&directory)?.is_dir(){return Err("fixture resolved ownership changed".into())}
  let marker=directory.join("fixture-owner");
  if !plain(&marker)?.is_file()||fs::read_to_string(&marker).map_err(|e|e.to_string())?!=self.marker{return Err("fixture owner marker changed".into())}
  // Inventory and validate everything before deleting anything. These files
  // belong only to this exclusively-created synthetic fixture and are fully
  // regenerated by its exact Rust test; source/lockfiles never live here.
  let mut files=Vec::new();let mut empty=Vec::new();
  for entry in fs::read_dir(&directory).map_err(|e|e.to_string())?{
   let entry=entry.map_err(|e|e.to_string())?;let path=entry.path();let name=entry.file_name();let name=name.to_str().ok_or("fixture filename encoding changed")?;
   if name=="fixture-owner"{continue}
   let m=plain(&path)?;
   if m.is_dir(){
    if name!="learned-memory-v1.json"||fs::read_dir(&path).map_err(|e|e.to_string())?.next().is_some(){return Err(format!("unexpected/nonempty fixture directory retained: {}",path.display()))}
    empty.push(path);continue
   }
   let pending=["goals.","learned-memory-v1."].iter().any(|prefix|name.strip_prefix(prefix)
    .and_then(|tail|tail.strip_suffix(".pending")).is_some_and(|id|id.len()==32&&id.bytes().all(|b|b.is_ascii_hexdigit())));
   if !m.is_file()||(!pending&&!matches!(name,"goals.json"|"learned-memory-v1.json"|"attempts.db"|"attempts.db-wal"|"attempts.db-shm"|"attempts.db-journal")){
    return Err(format!("unrecognized fixture path retained: {}",path.display()))
   }
   files.push((path,m.len()));
  }
  for (path,bytes) in files{fs::remove_file(&path).map_err(|e|format!("fixture cleanup failed, retained {}: {e}",path.display()))?;eprintln!("memory fixture removed {} ({bytes} logical bytes)",path.display())}
  for path in empty{fs::remove_dir(&path).map_err(|e|e.to_string())?;eprintln!("memory fixture removed empty {}",path.display())}
  let bytes=plain(&marker)?.len();fs::remove_file(&marker).map_err(|e|e.to_string())?;
  fs::remove_dir(&directory).map_err(|e|e.to_string())?;
  eprintln!("memory fixture removed {} ({bytes} marker bytes); Linux/Windows recovery not inferred",directory.display());Ok(())
 }
}
impl Drop for MemoryFixture{
 fn drop(&mut self){
  if std::thread::panicking(){eprintln!("memory fixture RETAINED for Root failure review: {}",self.directory.display());return}
  if let Err(error)=self.reconcile(){panic!("memory fixture retained for Root reconciliation at {}: {error}",self.directory.display())}
 }
}
