"use client";

export interface LearnedMemoryRow {
  id: string;
  version: number;
  content: string;
  provenance: { model: string; sources: { id: string; contentHash: string; chatId: string; kind: string }[] };
}
export interface ResetPreview { scopeHash: string; confirmation: string; count: number }

export function LearnedMemoryList({ scopeLabel, rows, total, pending, canForget, resetPreview, onPreviewReset, onConfirmReset, onForget, onNextPage }: {
  scopeLabel: string;
  rows: LearnedMemoryRow[];
  total: number;
  pending: boolean;
  canForget: boolean;
  resetPreview: ResetPreview | null;
  onPreviewReset: () => void;
  onConfirmReset: (confirmation: string) => void;
  onForget: (id: string, expectedVersion: number) => void;
  onNextPage?: () => void;
}) {
  return <section aria-label="Learned recall" className="space-y-3">
    <h3 className="font-medium">Learned recall</h3>
    <p>{scopeLabel}</p>
    <p className="text-sm text-[var(--text-muted)]">Inferred and potentially stale. Forgetting also removes summaries derived from the same sources. Saved memories can be edited in Saved memories.</p>
    {rows.length === 0 && <p>No learned recall in this scope.</p>}
    <ul className="space-y-3">{rows.map((row) => <li key={row.id} className="rounded-lg border border-[var(--border)] p-3">
      <p className="whitespace-pre-wrap break-words">{row.content}</p>
      <details><summary>Provenance · version {row.version}</summary>
        <p className="break-words">Generated by {row.provenance.model}</p>
        <ul>{row.provenance.sources.map((source) => <li key={source.id} className="break-words">{source.kind}: {source.id} · {source.contentHash}</li>)}</ul>
      </details>
      <button type="button" disabled={pending || !canForget} onClick={() => onForget(row.id, row.version)}>Forget this recall and its derivatives</button>
    </li>)}</ul>
    <p>{total} learned memories in this scope.</p>
    {onNextPage && <button type="button" disabled={pending} onClick={onNextPage}>Load more recall</button>}
    <button type="button" disabled={pending || !canForget} onClick={onPreviewReset}>Preview reset of learned recall</button>
    {resetPreview && <div role="group" aria-label="Confirm scoped memory reset" className="rounded-lg border border-[var(--border)] p-3">
      <p>Forget {resetPreview.count} learned memories in {scopeLabel}?</p>
      <p>Transcripts, saved memories, instructions, skills and computer history are retained. Immutable backups may retain old data until their separate expiry.</p>
      <button type="button" disabled={pending || !canForget} onClick={() => onConfirmReset(resetPreview.confirmation)}>Confirm reset of {resetPreview.count} learned memories</button>
    </div>}
  </section>;
}
